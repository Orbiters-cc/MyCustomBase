using System;
using UnityEditor;
#if ORBITERS_UNITGIT
using Orbiters.UnitGit.Editor;
#endif

/// <summary>
/// Bridges MCB version publication with Unit Git: when a version is uploaded, the published
/// files are saved and committed, and a generic release checkpoint is recorded so Unit Git can
/// display the release in its history even if MCB is later removed from the project.
/// </summary>
public static class UnitGitReleasePublisher
{
    public static bool IsUnitGitAvailable
    {
        get
        {
#if ORBITERS_UNITGIT
            return true;
#else
            return false;
#endif
        }
    }

    /// <summary>
    /// Connector test: generates a small dummy file and commits it through Unit Git, so the
    /// MCB ↔ Unit Git integration can be verified without publishing anything.
    /// </summary>
    public static bool TryCreateTestCommit(out string message)
    {
        message = string.Empty;
#if ORBITERS_UNITGIT
        try
        {
            string folder = "Assets/MCB/unitgit-test";
            System.IO.Directory.CreateDirectory(folder);
            string fileName = $"unitgit-test-{DateTime.Now:yyyy-MM-dd_HH-mm-ss}.txt";
            string filePath = folder + "/" + fileName;
            System.IO.File.WriteAllText(
                filePath,
                "Unit Git connector test file generated by MCB.\n" +
                $"Created: {DateTime.Now:O}\n" +
                "This file only exists to verify that MCB can create commits through Unit Git. It is safe to delete.\n");
            AssetDatabase.ImportAsset(filePath);

            // Commit only the generated file (and its metas), leaving other pending changes alone.
            var pathsToCommit = new System.Collections.Generic.List<string> { filePath };
            if (System.IO.File.Exists(filePath + ".meta")) pathsToCommit.Add(filePath + ".meta");
            if (System.IO.File.Exists(folder + ".meta")) pathsToCommit.Add(folder + ".meta");
            UnitGitReleaseResult result = UnitGitReleases.CommitFiles(
                "MCB : Unit Git connector test",
                $"Generated test file: {filePath}",
                pathsToCommit.ToArray());
            message = result.Success
                ? $"Test commit created ({ShortHash(result.CommitHash)}) with {fileName}."
                : result.Message;
            if (result.Success)
            {
                MCBLogger.Log($"[MCB] Unit Git connector test commit created: {result.CommitHash}");
            }
            else
            {
                MCBLogger.LogWarning($"[MCB] Unit Git connector test commit failed: {result.Message}");
            }

            return result.Success;
        }
        catch (Exception ex)
        {
            message = ex.Message;
            MCBLogger.LogWarning($"[MCB] Unit Git connector test commit failed: {ex.Message}");
            return false;
        }
#else
        message = "The Unit Git package (orbiters.unitgit) is not installed.";
        return false;
#endif
    }

    private static string ShortHash(string hash)
    {
        return string.IsNullOrEmpty(hash) ? "?" : (hash.Length > 8 ? hash.Substring(0, 8) : hash);
    }

    /// <summary>
    /// Saves pending assets, records the release in the Unit Git releases file, stages all
    /// changes and commits them as a release checkpoint. Never throws; returns false (with a
    /// message) when the checkpoint could not be created.
    /// </summary>
    public static bool TryPublishReleaseCheckpoint(CustomBaseVersion version, string assetName, out string message)
    {
        message = string.Empty;
#if ORBITERS_UNITGIT
        try
        {
            EditorUtility.DisplayProgressBar("Unit Git", "Creating release checkpoint commit...", 0.9f);
            AssetDatabase.SaveAssets();

            var entry = new UnitGitReleaseEntry
            {
                tool = "MCB",
                type = "mcb-version",
                name = string.IsNullOrWhiteSpace(assetName) ? "MCB Asset" : assetName.Trim(),
                version = version?.version ?? string.Empty,
                title = version?.title ?? string.Empty,
                changelog = version?.changelog ?? string.Empty,
                scope = version != null ? version.scope.ToString() : string.Empty,
                date = DateTime.UtcNow.ToString("o")
            };

            if (version != null)
            {
                if (version.assetId > 0)
                {
                    entry.fields.Add(new UnitGitReleaseField("Asset Id", version.assetId.ToString()));
                }

                if (!string.IsNullOrWhiteSpace(version.defaultAviVersion))
                {
                    entry.fields.Add(new UnitGitReleaseField("Default Avatar Version", version.defaultAviVersion));
                }

                if (!string.IsNullOrWhiteSpace(version.parentVersion))
                {
                    entry.fields.Add(new UnitGitReleaseField("Parent Version", version.parentVersion));
                }
            }

            string commitTitle = $"MCB : v{entry.version} - {entry.title}";
            UnitGitReleaseResult result = UnitGitReleases.PublishRelease(entry, commitTitle);
            message = result.Message;
            if (result.Success)
            {
                MCBLogger.Log($"[CreatorMode] Unit Git release checkpoint created for v{entry.version} (commit {result.CommitHash}).");
            }
            else if (OperationErrorClassifier.IsDiskFullMessage(result.Message))
            {
                message = OperationErrorReporter.Report(null, new OperationError
                {
                    Category = OperationErrorCategory.DiskFull,
                    UserMessage = DiskUtils.BuildDiskFullMessage("Creating the Unit Git release checkpoint"),
                    Detail = result.Message
                }, "Unit Git checkpoint");
                MCBLogger.LogWarning($"[CreatorMode] Unit Git release checkpoint failed (disk full): {result.Message}");
            }
            else
            {
                MCBLogger.LogWarning($"[CreatorMode] Unit Git release checkpoint failed: {result.Message}");
            }

            return result.Success;
        }
        catch (Exception ex)
        {
            if (OperationErrorClassifier.IsDiskFullError(ex))
            {
                message = OperationErrorReporter.Report(null, new OperationError
                {
                    Category = OperationErrorCategory.DiskFull,
                    UserMessage = DiskUtils.BuildDiskFullMessage("Creating the Unit Git release checkpoint"),
                    Detail = ex.ToString()
                }, "Unit Git checkpoint");
            }
            else
            {
                message = ex.Message;
            }

            MCBLogger.LogWarning($"[CreatorMode] Unit Git release checkpoint failed: {ex.Message}");
            return false;
        }
        finally
        {
            EditorUtility.ClearProgressBar();
        }
#else
        message = "The Unit Git package (orbiters.unitgit) is not installed.";
        return false;
#endif
    }
}
